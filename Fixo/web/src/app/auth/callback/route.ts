import { createClient } from '@/utils/supabase/server';
import { isVerifiedAdmin, sanitizeRedirectPath } from '@/utils/auth-role';
import { NextResponse } from 'next/server';

export async function GET(request: Request) {
  const { searchParams, origin } = new URL(request.url);
  const code = searchParams.get('code');
  const rawNext = searchParams.get('next');
  let next = sanitizeRedirectPath(rawNext, '/dashboard');

  if (code) {
    const supabase = await createClient();
    const { data, error } = await supabase.auth.exchangeCodeForSession(code);
    if (!error && data?.user) {
      const isAdmin = isVerifiedAdmin(data.user);

      // If logging in as verified Admin/Owner, direct them straight to /admin
      if (isAdmin && (!rawNext || next === '/dashboard')) {
        next = '/admin';
      }

      const forwardedHost = request.headers.get('x-forwarded-host');
      const isLocalEnv = process.env.NODE_ENV === 'development';
      if (isLocalEnv) {
        return NextResponse.redirect(`${origin}${next}`);
      } else if (forwardedHost) {
        return NextResponse.redirect(`https://${forwardedHost}${next}`);
      } else {
        return NextResponse.redirect(`${origin}${next}`);
      }
    }
  }

  return NextResponse.redirect(`${origin}/login?error=oauth_error`);
}
